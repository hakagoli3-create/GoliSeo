                specs.add(Pair("بافت و فینیش", "سبک، زودجذب، فاقد چربی مازاد و بدون بر جای گذاشتن رد سفیدی"))
                specs.add(Pair("زمان استفاده", "۱۵ الی ۲۰ دقیقه پیش از قرار گرفتن در معرض آفتاب"))
                specs.add(Pair("دوره تمدید", "هر ۲ ساعت یک‌بار و پس از شستشو یا تعریق شدید"))
            }
            ProductArchetype.SKIN_MOISTURIZER -> {
                specs.add(Pair("زمان مصرف", "صبح و شب در روتین پوستی روزانه روی پوست تمیز"))
                specs.add(Pair("بافت محصول", "کرم آبرسان سبک با جذب عمقی بدون احساس چربی سنگین"))
