            ProductArchetype.HAIR_MASK -> {
                specs.add(Pair("نیاز به آبکشی", "بله (آبکشی کامل ساقه مو با آب ولرم)"))
                specs.add(Pair("موضع مجاز مصرف", "منحصراً ساقه و انتهای مو (اکیداً روی ریشه و کف سر مالیده نشود)"))
                specs.add(Pair("زمان مکث در حمام", "۳ الی ۵ دقیقه پس از شامپو"))
                specs.add(Pair("سازگاری با انواع مو", "موهای خشک، آسیب‌دیده، رنگ‌شده، دکلره و کراتینه‌شده"))
