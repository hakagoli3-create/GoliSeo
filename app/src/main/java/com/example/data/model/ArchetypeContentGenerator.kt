/**
 * تولیدکننده محتوای تخصصی و تفکیک‌شده سئو بر پایه داده‌های تأییدشده هر محصول (Zero Hallucination)
 * بدون سرایت اطلاعات بین‌دسته‌ای، با جدول مشخصات اختصاصی، راهنمای مصرف، هشدارها، پرسش‌های متداول و متون تصمیم خرید.
