        specs.add(Pair("نام و استاندارد کالا", normalizedTitle))
        specs.add(Pair("برند اصلی سازنده", analysis.detectedBrand))
        specs.add(Pair("کشور مبدا و تولید", analysis.originCountry))
        specs.add(Pair("عرضه کننده و مرجع خرید", agencyLabel))
        specs.add(Pair("نوع محصول و فرمولاسیون", analysis.productType))
        specs.add(Pair("بافت هدف و سطوح مصرف", analysis.targetSurfaceOrTissue))

        when (analysis.archetype) {
            ProductArchetype.HAIR_SHAMPOO -> {
                specs.add(Pair("نیاز به آبکشی", "بله (آبکشی کامل با آب ولرم پس از ۲ دقیقه ماساژ)"))
                specs.add(Pair("موضع مجاز مصرف", "کف سر و تارهای خیس مو در حمام"))
                specs.add(Pair("ویژگی شاخص شویندگی", "کنترل چربی سبوم پوست سر بدون آسیب به رطوبت فیبر مو"))
                specs.add(Pair("پرهیز مصرفی", "عدم تماس با چشم (در صورت تماس، شستشو با آب سرد فراوان)"))
