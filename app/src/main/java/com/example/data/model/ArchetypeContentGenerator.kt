object ArchetypeContentGenerator {

    fun generateShortDescription(analysis: ProductPreAnalysis): String {
        val brand = analysis.detectedBrand
        val country = analysis.originCountry
        val agencyText = if (analysis.isOfficialAgencyBrand) {
            "گلی کالا نماینده رسمی و انحصاری محصولات برندهای آمالفی، آگرادو و سایرو در ایران"
        } else {
            "گلی کالا (واردکننده رسمی و مرجع اصالت کالا)"
        }

        val text = when (analysis.archetype) {
            ProductArchetype.HAIR_SHAMPOO ->
                "شامپو تخصصی $brand ساخت $country فرموله‌شده برای شستشوی ملایم مو و کنترل چربی مازاد پوست سر در حمام، بدون ایجاد حس خشکی یا شکنندگی در ساقه مو. دارای کف ملایم و آبکشی سریع با تضمین اصالت ۱۰۰٪ فیزیکی در گلی کالا ($agencyText)."

            ProductArchetype.HAIR_MASK ->
                "ماسک مو تخصصی $brand ساخت $country طراحی‌شده منحصراً برای تغذیه، نرم‌کنندگی و ترمیم عمقی فیبر و کوتیکول ساقه و نوک موهای خشک، رنگ‌شده یا آسیب‌دیده در حمام (بدون تماس با ریشه و کف سر) با مکث ۳ الی ۵ دقیقه‌ای و آبکشی کامل با ضمانت اصالت در گلی کالا."

            ProductArchetype.HAIR_SERUM_BIPHASIC ->
                "اسپری سرم دوفاز ضد وز و محافظ حرارتی $brand ساخت $country جهت محافظت از تارهای مو در برابر گرمای سشوار و اتو و مهار الکتریسیته ساکن ساقه مو بدون نیاز به آبکشی (Leave-in) با بافت سبک و جذب سریع در گلی کالا."

            ProductArchetype.INTIMATE_HYGIENE ->
                "ژل بهداشتی بانوان $brand ساخت $country با فرمولاسیون هایپوآلرژنیک و فاقد صابون، سازگار با pH فیزیولوژیک جهت حفظ تعادل فلور محافظتی، رفع بوی نامطبوع و پیشگیری از خشکی و سوزش (منحصراً استعمال موضعی خارجی) با گارانتی اصالت در گلی کالا."

            ProductArchetype.BODY_LOTION ->
                "لوسیون بدن آبرسان و مغذی ۲۴ ساعته $brand ساخت $country با بافت امولسیونی سبک و زودجذب جهت رفع فوری خشکی و کشیدگی پوست بدن پس از استحمام، ایجاد لطافت ابریشمی بدون باقی گذاشتن حس چربی با ضمانت اصالت در گلی کالا."

            ProductArchetype.HAND_AND_NAIL ->
                "کرم مرطوب‌کننده دست و تقویت‌کننده کوتیکول ناخن $brand ساخت $country با فرمول مغذی جهت ترمیم زبری و خشکی پوست دست و افزایش استحکام ناخن‌ها با جذب سریع و فرمولاسیون غیرچرب در گلی کالا."

            ProductArchetype.SKIN_SUNSCREEN ->
                "کرم ضد آفتاب $brand ساخت $country با فیلترهای پیشرفته وسیع‌الطیف UVA و UVB جهت محافظت حداکثری پوست در برابر پرتوهای آفتاب، پیری زودرس و لک‌های پوستی، با بافت سبک، زودجذب و فاقد رد سفیدی در گلی کالا."

            ProductArchetype.SKIN_MOISTURIZER ->
                "کرم آبرسان عمقی و مرطوب‌کننده بافت پوست $brand ساخت $country جهت آبرسانی لایه‌های اپیدرم، رفع خشکی و حفظ سد دفاعی چهره در روتین روز و شب با ماندگاری رطوبت بالا در گلی کالا."

            ProductArchetype.SKIN_SERUM ->
                "سرم تخصصی و فعال پوست $brand ساخت $country حاوی ترکیبات کنسانتره مغذی با قدرت نفوذ بسیار بالا به عمق لایه‌های پوستی جهت روشن‌کنندگی و بازسازی بافت چهره پیش از مرطوب‌کننده با ضمانت اصالت در گلی کالا."

            ProductArchetype.SKIN_CLEANSER_TONER ->
                "تونر پاکسازی منافذ و تنظیم‌کننده بافت پوست $brand ساخت $country جهت زدودن باقیمانده آلودگی‌ها، کنترل سبوم و تنظیم pH طبیعی پوست بدون احساس کشیدگی با گارانتی اصالت در گلی کالا."

            ProductArchetype.DETERGENT_DESCALER ->
                "رسوب‌زدا و جرم‌گیر فوق‌العاده قوی $brand ساخت $country فرموله‌شده برای حل فوری رسوبات کهنه آهک و جرم شیرآلات، کاشی، سرامیک و کتری در ۲ الی ۵ دقیقه. الزام به استفاده از دستکش و ممنوعیت مطلق اختلاط با وایتکس با ضمانت اصالت در گلی کالا."

            ProductArchetype.DETERGENT_DEGREASER ->
                "اسپری پاک‌کننده و چربی‌زدای تخصصی $brand ساخت $country جهت تجزیه فوری لایه‌های چربی سوخته و دوده روی اجاق گاز، فیلتر هود و دیواره فر در ۱ الی ۳ دقیقه بدون آسیب به سطوح استاندارد (استفاده از دستکش الزامی است) در گلی کالا."

            ProductArchetype.DETERGENT_DISHWASHER ->
                "شوینده پرقدرت ماشین ظرفشویی $brand ساخت $country جهت چربی‌زدایی سریع از ظروف بلور و استیل، رفع لکه‌های سخت خشکیده غذا و درخشش بدون خط و خش ظروف با ضمانت اصالت در گلی کالا."

            ProductArchetype.DETERGENT_GLASS ->
                "اسپری شیشه‌شوی تخصصی ضد بخار $brand ساخت $country با قدرت پاک‌کنندگی سریع و تبخیر بدون رد، فاقد هرگونه رگه، لکه یا ماتی روی شیشه و آینه‌ها با گارانتی اصالت در گلی کالا."

            ProductArchetype.DETERGENT_SURFACE ->
                "شوینده و ضدعفونی‌کننده بهداشتی سطوح سخت $brand ساخت $country مناسب کفپوش، سنگ و سرامیک جهت زدودن آلودگی‌ها و ایجاد درخشش بهداشتی در منزل با ضمانت اصالت در گلی کالا."

            ProductArchetype.ORAL_CARE ->
                "خمیر دندان تخصصی $brand ساخت $country جهت محافظت از مینای دندان در برابر اسیدهای پوسیدگی، پاکسازی پلاک‌های میکروبی و ایجاد طراوت ماندگار دهان با فرمولاسیون استاندارد در گلی کالا."

            ProductArchetype.DEODORANT ->
                "دئودورانت و رولان ضد تعریق ۲۴ ساعته $brand ساخت $country با ماندگاری بالا، مهار بوی نامطبوع تعریق بدون مسدود کردن غیرطبیعی منافذ پوست و بدون ایجاد لکه روی البسه با ضمانت اصالت در گلی کالا."

            ProductArchetype.GENERAL_STANDARD ->
                "محصول استاندارد بهداشتی $brand ساخت $country منطبق با استانداردهای رسمی بهداشتی اروپا و تضمین ۱۰۰٪ اصالت فیزیکی، دارای بارکد رسمی بین‌المللی در فروشگاه گلی کالا."
        }
        return PersianNormalizer.normalize(text)
    }

    fun generateSpecificationsTable(
        analysis: ProductPreAnalysis,
        normalizedTitle: String,
        agencyLabel: String
    ): List<Pair<String, String>> {
