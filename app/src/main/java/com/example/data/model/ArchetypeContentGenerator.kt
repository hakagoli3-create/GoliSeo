    fun generateRankMathMeta(analysis: ProductPreAnalysis, keyword: String): String {
        val brand = analysis.detectedBrand
        val agencyText = if (analysis.isOfficialAgencyBrand) {
            "گلی کالا (نماینده رسمی آمالفی، آگرادو و سایرو)"
        } else {
            "گلی کالا (واردکننده رسمی و مرجع اصالت کالا)"
        }

        val text = when {
            analysis.isDetergentOrCleaner ->
                "خرید $keyword اصل $brand در گلی کالا ($agencyText). مشخصات فنی، روش مصرف، هشدارهای ایمنی و ضمانت اصالت ۱۰۰٪."
            analysis.isOfficialAgencyBrand ->
                "خرید $keyword اصل $brand در گلی کالا ($agencyText). مشخصات فنی، ترکیبات، نحوه مصرف و ضمانت اصالت ۷ روزه."
            else ->
                "خرید اینترنتی $keyword اصل $brand با گارانتی اصالت در گلی کالا. مشخصات کامل، جدول ترکیبات و ارسال سریع به سراسر ایران."
        }
        return PersianNormalizer.normalize(text).take(155)
    }

